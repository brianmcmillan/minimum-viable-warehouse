#!/usr/bin/env bash
# =====================================================================
# Write MANIFEST.md: every file in the repo, in the layout
# `tree -a --gitignore --dirsfirst` prints.
#
# The file list is git's: tracked files that still exist plus untracked
# files .gitignore does not exclude, so the generated databases, logs,
# .DS_Store and .claude/ never appear. It is drawn here with awk rather
# than by tree itself, because tree is not a stock tool and its output
# depends on the locale (line characters, spacing and sort order); this
# gives the same bytes on every machine. Directories come first at each
# level, then names compared lowercased, byte by byte, so the order can
# differ from tree's where names differ only in punctuation. The count
# is of directories that hold at least one listed file.
#
#   usage: tools/manifest.sh        (or)        make manifest
# Exit 2: not in a git work tree. Written for bash 3.2 and POSIX awk.
# =====================================================================
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT" || exit 2
git rev-parse --is-inside-work-tree >/dev/null 2>&1 || {
  echo "manifest: not in a git work tree" >&2; exit 2; }

TMP="$(mktemp)"; trap 'rm -f "$TMP"' EXIT

{ git ls-files; git ls-files --others --exclude-standard; echo MANIFEST.md; } |
  while IFS= read -r p; do [ -f "$p" ] && printf '%s\n' "$p"; done |
  LC_ALL=C sort -u |
  # Sort key: each directory component as "0<lowercased name>", the
  # file as "1<lowercased name>", joined by \001, then the path itself.
  LC_ALL=C awk '{ n = split($0, c, "/"); k = ""
                  for (i = 1; i <= n; i++) k = k (i < n ? "0" : "1") tolower(c[i]) "\001"
                  print k "\t" $0 }' |
  LC_ALL=C sort | cut -f2 |
  LC_ALL=C awk '
    # Emit each directory the first time it is seen, then the file.
    { n = split($0, c, "/"); path = ""
      for (i = 1; i <= n; i++) {
        path = path (i > 1 ? "/" : "") c[i]
        if (i < n && (path in seen)) continue
        seen[path] = 1; m++; name[m] = c[i]; depth[m] = i; isdir[m] = (i < n)
        if (i < n) dirs++; else files++
      } }
    END {
      # A node is the last of its siblings when the next node at its
      # depth or shallower is shallower (or there is none).
      for (j = 1; j <= m; j++) {
        last[j] = 1
        for (k = j + 1; k <= m; k++) {
          if (depth[k] < depth[j]) break
          if (depth[k] == depth[j]) { last[j] = 0; break } } }
      print "."
      for (j = 1; j <= m; j++) {
        d = depth[j]; lastat[d] = last[j]; pre = ""
        for (i = 1; i < d; i++) pre = pre (lastat[i] ? "    " : "│   ")
        print pre (last[j] ? "└── " : "├── ") name[j] }
      print ""
      printf "%d directories, %d files\n", dirs, files }' > "$TMP" || exit 1

{ printf '# Manifest\n\n'
  printf 'Every file in the repo. Generated by `make manifest`, which `make all`\n'
  printf 'runs; do not edit by hand. Generated databases and logs are left out,\n'
  printf 'as `.gitignore` leaves them out of git.\n\n'
  printf '```text\n'; cat "$TMP"; printf '```\n'; } > "$TMP.md" || exit 1
mv "$TMP.md" MANIFEST.md
echo "Wrote MANIFEST.md ($(tail -1 "$TMP"))."
